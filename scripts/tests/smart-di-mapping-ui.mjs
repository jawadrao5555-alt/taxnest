// Runs the real Blade bulk-import component, without Laravel or any regulator requests.
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const blade = readFileSync(new URL('../../resources/views/invoice/index.blade.php', import.meta.url), 'utf8');
const source = blade.slice(blade.indexOf('function bulkImport()'), blade.indexOf('</script>', blade.indexOf('function bulkImport()'))).replace(/\{\{[^\n]*?\}\}/g, 'false');
const requests = [];
const ctx = {setInterval, clearInterval, document: {querySelector: () => ({content: 'local-test'})}, fetch: async (url, options) => {
    requests.push({url, payload: JSON.parse(options.body)});
    return {ok: true, json: async () => ({batch_id: 1, preview: [], total: 1, valid_count: 1, error_count: 0})};
}};
vm.createContext(ctx); vm.runInContext(source, ctx);
const component = ctx.bulkImport();
const fields = ['buyer_name', 'quantity', 'document_type'].map(key => ({key, value_required: true}));
const presets = [{id: 7, name: 'Local test', matches: true, mapping: {buyer_name: 'Outlet Name', quantity: 'Qty'}, defaults: {document_type: 'Sale Invoice'}}];
const data = {mapping_token: 'x'.repeat(40), headers: ['Qty', 'outlet-name', 'Corrected Outlet'], fields, presets, smart_mapping_enabled: true, recommended_preset_id: 7};
component.setupMapping(data);
assert.equal(component.step, 'mapping');
assert.equal(component.mappingSel.buyer_name, 'outlet-name');
assert.equal(component.defaultsSel.document_type, 'Sale Invoice');
assert.equal(requests.length, 0, 'Recognizing/selecting a format must make no request');
component.mappingSel.buyer_name = 'Corrected Outlet';
await component.applyMapping();
assert.equal(requests[0].url, '/invoices/import-apply-mapping');
assert.equal(requests[0].payload.mapping.buyer_name, 'Corrected Outlet');
assert.equal(requests[0].payload.preset_id, undefined, 'Manual corrections must not be overwritten by the saved preset');
assert.equal(requests[0].payload.defaults.document_type, 'Sale Invoice');
assert.equal(component.step, 'preview');
component.setupMapping({...data, recommended_preset_id: null, format_match_reason: 'ambiguous_presets', suggestions: {}});
assert.equal(component.mappingSel.buyer_name, '');
assert.match(component.formatMatchNotice, /Several/);
component.selectMappingPreset(7);
assert.equal(component.mappingSel.quantity, 'Qty');
component.setupMapping({...data, headers: ['Qty', 'Outlet Name', 'outlet-name']});
assert.equal(component.mappingSel.buyer_name, '', 'Duplicate normalized headers require correction');
component.setupMapping({...data, smart_mapping_enabled: false, suggestions: {buyer_name: 'Corrected Outlet'}});
assert.equal(component.mappingSel.buyer_name, 'Corrected Outlet', 'Flag off keeps legacy suggestions');
component.resetUpload();
assert.equal(component.recommendedPresetId, null);
assert.equal(component.smartMappingEnabled, false);
assert.equal(requests.length, 1);
console.log('Smart DI mapping component regressions passed');
